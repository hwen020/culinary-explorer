import {expect, test} from '@playwright/test'

test.beforeEach(async ({page}) => {
  page.on('pageerror', error => console.error('Browser exception:', error.message))
  page.on('console', message => {
    if (message.type() === 'error') console.error('Browser console:', message.text())
  })
  page.on('requestfailed', request => console.error('Browser request failed:', request.url(), request.failure()?.errorText))
  page.on('response', response => {
    if (response.url().includes('/api/')) console.log('API:', response.status(), new URL(response.url()).pathname)
  })
})

test('register, sign in, explore, save, map, restore chat, and sign out', async ({page, request}) => {
  const email = 'browser-' + Date.now() + '@example.test'
  const health = page.waitForResponse(response => response.url().endsWith('/api/health'), {timeout: 25000})
  await page.goto('/', {waitUntil: 'domcontentloaded'})
  expect((await health).status()).toBe(200)
  await expect(page.getByRole('heading', {name: 'Find your next favorite table.'})).toBeVisible()
  await expect(page.getByText('Demonstration mode')).toBeVisible()
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await page.getByRole('button', {name: 'Create account'}).click()
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', {exact: true}).fill('browser password only')
  await page.getByRole('button', {name: 'Register', exact: true}).click()
  await expect(page.getByRole('status')).toContainText('Account created')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', {exact: true}).fill('browser password only')
  await page.locator('main').getByRole('button', {name: 'Sign in', exact: true}).click()
  await page.getByLabel('City or address').fill('Monrovia, CA')
  await page.getByLabel('Radius').fill('1')
  await page.getByLabel('Unit').selectOption('km')
  await page.getByLabel('Cuisine or name').fill('Chinese')
  await page.getByLabel('Minimum rating').selectOption('4.5')
  await page.getByLabel('Price', {exact: true}).selectOption('2')
  await page.getByRole('button', {name: 'Find restaurants'}).click()
  await expect(page.getByRole('heading', {name: '1 restaurants'})).toBeVisible()
  await page.getByRole('button', {name: 'Save Sample Noodle House'}).click()
  await expect(page.getByRole('button', {name: 'Unsave Sample Noodle House'})).toBeVisible()
  const csv = page.waitForEvent('download')
  await page.getByRole('button', {name: 'Download CSV'}).click()
  expect((await csv).suggestedFilename()).toBe('restaurants.csv')
  await page.getByRole('button', {name: 'Map', exact: true}).click()
  await page.getByLabel('Illustrative demo map').getByRole('button', {name: 'Sample Noodle House'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('link', {name: 'Directions to illustrative coordinates'})).toHaveAttribute('href', /google.com\/maps\/dir/)
  await page.getByRole('button', {name: 'Close details'}).click()
  await page.getByRole('button', {name: 'Chat', exact: true}).click()
  await page.getByLabel('Your question').fill('Chinese restaurants above 4.5?')
  await page.getByRole('button', {name: 'Ask', exact: true}).click()
  await expect(page.getByText(/Matching options: Sample Noodle House/)).toBeVisible()
  await expect(page.getByText(/No AI model generated this answer/)).toBeVisible()
  await page.reload()
  await page.getByRole('button', {name: 'Explore', exact: true}).click()
  await page.getByRole('button', {name: 'Chinese restaurants above 4.5?'}).click()
  await expect(page.getByText(/Matching options: Sample Noodle House/)).toBeVisible()
  await page.getByRole('button', {name: 'Saved', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Sample Noodle House'})).toBeVisible()
  await page.getByRole('button', {name: 'Account', exact: true}).click()
  await page.getByRole('button', {name: 'Sign out', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Sign in'})).toBeVisible()
  expect((await page.request.get('/api/favorites')).status()).toBe(401)
  expect((await request.get('/api/users/me')).status()).toBe(401)
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', {exact: true}).fill('browser password only')
  await page.locator('main').getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Explore restaurants'})).toBeVisible()
  await page.getByRole('button', {name: 'Saved', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Sample Noodle House'})).toBeVisible()
})

test('mobile plans and discovery fit the viewport', async ({page}) => {
  await page.setViewportSize({width: 375, height: 800})
  await page.goto('/')
  await page.getByRole('button', {name: 'Plans', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'premium'})).toBeVisible()
  await expect(page.getByRole('button', {name: 'Choose premium'})).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
})
